/*
Operadores Lógicos

&& = AND = (E)

|| = OR = (OU)

! = NOT = (NÃO)

*/

/*
TUDO PRECISA SER VERDADEIRO

true && true   // true
true && false  // false
false && true  // false
false && false // false

let idade = 20;
let temCarteira = true;

idade >= 18 && temCarteira // true

*/

/*
BASTA UM SER VERDADEIRO

true || true   // true
true || false  // true
false || true  // true
false || false // false

let temDinheiro = false;
let temPix = true;

temDinheiro || temPix // true

*/

/*
INVERTE O VALOR

!true  // false
!false // true

let logado = false;

!logado // true

*/

